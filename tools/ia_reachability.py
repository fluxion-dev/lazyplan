#!/usr/bin/env python3
"""Generate the machine-checked reachability report for the IA registry.

Stdlib only. ``--check`` fails when the committed JSON and Markdown are stale.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT_DIR = ROOT / "docs" / "information-architecture"
JSON_FILE = OUT_DIR / "reachability.json"
MARKDOWN = OUT_DIR / "reachability.md"


def report() -> dict:
    """Live registry report."""
    if str(SRC) not in sys.path:
        sys.path.insert(0, str(SRC))
    from lazyplan.presentation.shared import registry

    return registry.reachability_report()


def markdown(payload: dict) -> str:
    """Human report with every action route and its depth."""
    lines = [
        "# Reachability report",
        "",
        "Generated by `tools/ia_reachability.py`. Do not edit by hand; run",
        "`python3 tools/ia_reachability.py --write` after changing a route.",
        "",
        f"Budget: every action is at most **{payload['max_depth']}** interactions from the tree.",
        "",
        "## Entity depth",
        "",
        "| Entity | Depth |",
        "| --- | ---: |",
    ]
    for entity, depth in payload["entities"].items():
        lines.append(f"| `{entity}` | {depth if depth is not None else '—'} |")
    lines.extend(
        [
            "",
            "## Action routes",
            "",
            "| Action | Route | Depth |",
            "| --- | --- | ---: |",
        ]
    )
    for row in payload["actions"]:
        route = " › ".join(row["route"])
        lines.append(f"| `{row['id']}` | {route} | {row['depth']} |")
    lines.extend(["", "## Over budget", ""])
    if payload["over_budget"]:
        lines.extend(f"- {error}" for error in payload["over_budget"])
    else:
        lines.append("None. Every action is within the three-interaction budget.")
    return "\n".join(lines) + "\n"


def rendered() -> tuple[str, str]:
    payload = report()
    return json.dumps(payload, indent=2, sort_keys=True) + "\n", markdown(payload)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="write the committed report")
    group.add_argument("--check", action="store_true", help="fail when the report is stale")
    args = parser.parse_args(argv)
    payload_json, payload_markdown = rendered()
    if args.write:
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        JSON_FILE.write_text(payload_json, encoding="utf-8")
        MARKDOWN.write_text(payload_markdown, encoding="utf-8")
        print(f"wrote {JSON_FILE.relative_to(ROOT)} and {MARKDOWN.relative_to(ROOT)}")
        return 0
    stale = []
    if not JSON_FILE.is_file() or JSON_FILE.read_text(encoding="utf-8") != payload_json:
        stale.append(str(JSON_FILE.relative_to(ROOT)))
    if not MARKDOWN.is_file() or MARKDOWN.read_text(encoding="utf-8") != payload_markdown:
        stale.append(str(MARKDOWN.relative_to(ROOT)))
    if stale:
        print("stale reachability report: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("reachability report is current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
